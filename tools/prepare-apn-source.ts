// Maintainer-only refresh. Normal package builds use the checked-in database offline.
import { mkdir, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { apnDatabaseUrl } from '../openwrt/apn-database.ts'
import { compileProviderDatabase } from '../shared/apn-database.ts'

const root='https://darthanwalt.github.io/openwrt-apn-autoconfig/providers/'
const files: Record<string,string>={}
for (const name of ['NOTICE','Apache-2.0.txt','MBPI-CC-PDDC.txt']) {
  const response=await fetch(root+name)
  if (!response.ok) throw new Error(`APN source ${name}: HTTP ${response.status}`)
  files[name]=await response.text()
}
const response=await fetch(apnDatabaseUrl)
if (!response.ok) throw new Error('APN database fetch failed: '+response.status)
const raw=await response.text(), database=compileProviderDatabase(raw)
const upstream_sha256=createHash('sha256').update(raw).digest('hex')
const {entries,...metadata}=database
await mkdir('data',{recursive:true})
await writeFile('data/apn-database.ts',[
  '// Generated by tools/prepare-apn-source.ts; do not edit individual rows here.',
  '// Source: '+apnDatabaseUrl,
  '// Modified GNOME MBPI + AOSP data. Redistribution notices: docs/apn-source.ts.',
  "import type { ProviderApnDatabase } from '../shared/apn-database.ts'",
  '',
  'export const bundledApnDatabase: ProviderApnDatabase & { upstream_sha256: string } = {',
  ...Object.entries({...metadata,upstream_sha256}).map(([key,value])=>'  '+key+': '+JSON.stringify(value)+','),
  '  entries: [',
  ...entries.map(entry=>'    '+JSON.stringify(entry)+','),
  '  ],',
  '}',
  '',
].join('\n'))
await writeFile('docs/apn-source.ts','// Upstream redistribution notices, kept verbatim. See NOTICE for attribution.\nexport const apnSourceNotices = '+JSON.stringify(files,null,2)+'\n')
await mkdir('build/apn-research',{recursive:true})
await writeFile('build/apn-research/providers.tsv',raw)
console.log(JSON.stringify({version:database.version,entries:database.count,upstream_sha256,bundled:'data/apn-database.ts'}))
